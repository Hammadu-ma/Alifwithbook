/* =========================================================================
   ALIF Med — service worker
   1. OFFLINE APP SHELL   : every file the app needs to boot is precached as one
                            atomic, versioned set (index.html, all menus/*.js,
                            CSS, fonts, icons). Boot is instant and works with
                            no network at all.
   2. RUNTIME CACHE       : Firebase SDK / marked / DOMPurify (versioned CDN
                            URLs) are cached forever after first use; other
                            static assets are stale-while-revalidate.
   3. WEB PUSH            : unchanged notification handlers.

   `BUILD` and the SHELL list below are generated by `node tools/stamp-sw.mjs`
   (runs automatically on `firebase deploy` via firebase.json "predeploy").
   Any change to any shipped file changes BUILD -> the browser installs the new
   worker -> the whole new shell is downloaded into a NEW cache before it takes
   over, so users never run a half-updated mix of old and new modules.

   Firestore / Auth / push-API traffic is never touched by this worker.
   ========================================================================= */
