/* ------------------------------------------------------------------ install */
self.addEventListener('install', event => {
  event.waitUntil((async () => {
    const cache = await caches.open(SHELL_CACHE);
    // Core shell: must all succeed, otherwise the install fails and the previous worker keeps serving (atomic update).
    await fetchInto(cache, SHELL, { mustSucceed: true, concurrency: 8 });
    // Nice-to-have (fonts, logos, 3rd-party libs): best effort, never blocks the update.
    await fetchInto(cache, SOFT, { mustSucceed: false, concurrency: 4 });
    await warmThirdParty();
    await self.skipWaiting();
  })());
});

/* A response that came through a redirect (e.g. Vercel's cleanUrls turns /index.html into /) is flagged
   `redirected`. Browsers refuse to show such a response for a page load that the service worker answers,
   which is a permanent ERR_FAILED on every refresh. Re-wrap it so the flag is dropped. */
async function cleanResponse(res) {
  if (!res.redirected) return res;
  const body = await res.blob();
  return new Response(body, { status: res.status, statusText: res.statusText, headers: res.headers });
}

async function fetchInto(cache, urls, { mustSucceed, concurrency }) {
  const queue = urls.slice();
  const worker = async () => {
    while (queue.length) {
      const url = queue.shift();
      try {
        // 'no-cache' = revalidate with the server (cheap 304) but never trust a stale HTTP-cache copy.
        const res = await fetch(new Request(url, { cache: 'no-cache', credentials: 'same-origin' }));
        if (!res.ok) throw new Error(url + ' -> ' + res.status);
        await cache.put(url, await cleanResponse(res));
      } catch (err) {
        if (mustSucceed) throw err;
      }
    }
  };
  await Promise.all(Array.from({ length: Math.min(concurrency, queue.length) }, worker));
}

// Pre-warm versioned CDN modules (+ what they import) so the very first offline launch already works.
async function warmThirdParty() {
  try {
    const cache = await caches.open(RUNTIME_CACHE);
    const seen = new Set();
    const queue = THIRD_PARTY.map(u => [u, 0]);
    while (queue.length && seen.size < 60) {
      const [url, depth] = queue.shift();
      if (seen.has(url)) continue;
      seen.add(url);
      let res = await cache.match(url);
      if (!res) {
        try { res = await fetch(url, { mode: 'cors', credentials: 'omit' }); } catch (_) { continue; }
        if (!res || !res.ok) continue;
        await cache.put(url, res.clone());
      }
      if (depth < 3 && /\.m?js(\?|$)/.test(url)) {
        const text = await res.clone().text();
        for (const m of text.matchAll(/(?:from|import)\s*["']([^"']+)["']/g)) {
          let next; try { next = new URL(m[1], url); } catch (_) { continue; }
          if (CACHEABLE_HOSTS.has(next.host) && !seen.has(next.href)) queue.push([next.href, depth + 1]);
        }
      }
    }
  } catch (_) {}
}

/* ----------------------------------------------------------------- activate */
self.addEventListener('activate', event => {
  event.waitUntil((async () => {
    const keys = await caches.keys();
    await Promise.all(keys
      .filter(k => (k.startsWith('alif-shell-') && k !== SHELL_CACHE))
      .map(k => caches.delete(k)));
    await self.clients.claim();
  })());
});

self.addEventListener('message', event => {
  const type = event.data && event.data.type;
  if (type === 'SKIP_WAITING') self.skipWaiting();
  if (type === 'CLEAR_CACHES') event.waitUntil(caches.keys().then(ks => Promise.all(ks.filter(k => k.startsWith('alif-')).map(k => caches.delete(k)))));
});

/* -------------------------------------------------------------------- fetch */
self.addEventListener('fetch', event => {
  const req = event.request;
  if (req.method !== 'GET' || req.headers.has('range')) return;
  let url;
  try { url = new URL(req.url); } catch (_) { return; }
  if (url.protocol !== 'https:' && url.protocol !== 'http:') return;

  if (url.origin === self.location.origin) {
    if (url.pathname === '/sw.js') return;                      // always straight to network
    if (req.mode === 'navigate') return void event.respondWith(handleNavigation(req, url));
    return void event.respondWith(handleSameOrigin(req, url));
  }
  if (CACHEABLE_HOSTS.has(url.host)) {
    const swr = url.host === 'fonts.googleapis.com';
    return void event.respondWith(swr ? staleWhileRevalidate(req, RUNTIME_CACHE) : cacheFirst(req, RUNTIME_CACHE));
  }
  // Everything else (Firestore, Auth, push API, Telegram, remote images…) is left to the network.
});

async function shellMatch(pathOrReq) {
  const cache = await caches.open(SHELL_CACHE);
  return cache.match(pathOrReq, { ignoreSearch: true });
}

async function handleNavigation(req, url) {
  // The app is a single-page shell: '/', '/index.html' (and cleanUrls variants) are served from the precache.
  const isEntry = url.pathname === '/' || url.pathname === '/index.html' || url.pathname === '/index';
  if (isEntry) {
    const hit = await shellMatch(SHELL_ENTRY);
    if (hit) return cleanResponse(hit);
  }
  try {
    return await fetch(req);
  } catch (_) {
    const hit = await shellMatch(SHELL_ENTRY);
    return (hit && await cleanResponse(hit)) || new Response(OFFLINE_HTML, { status: 200, headers: { 'Content-Type': 'text/html; charset=utf-8' } });
  }
}

async function handleSameOrigin(req, url) {
  const hit = await shellMatch(req);                              // precached: instant, offline-proof
  if (hit) return hit;
  const isAsset = url.pathname.startsWith('/assets/') || /\.(?:png|jpe?g|webp|svg|ico|woff2?|json|webmanifest)$/i.test(url.pathname);
  if (isAsset) return staleWhileRevalidate(req, RUNTIME_CACHE);
  try { return await fetch(req); }
  catch (err) {
    const cache = await caches.open(RUNTIME_CACHE);
    const stale = await cache.match(req);
    if (stale) return stale;
    throw err;
  }
}

async function cacheFirst(req, cacheName) {
  const cache = await caches.open(cacheName);
  const hit = await cache.match(req);
  if (hit) return hit;
  const res = await fetch(req);
  if (res && res.ok && res.type !== 'opaque') { cache.put(req, res.clone()).then(() => trim(cache)).catch(() => {}); }
  return res;
}

async function staleWhileRevalidate(req, cacheName) {
  const cache = await caches.open(cacheName);
  const hit = await cache.match(req);
  const refresh = fetch(req).then(res => {
    if (res && res.ok && res.type !== 'opaque') { cache.put(req, res.clone()).then(() => trim(cache)).catch(() => {}); }
    return res;
  }).catch(() => null);
  if (hit) { refresh.catch(() => {}); return hit; }
  const res = await refresh;
  if (res) return res;
  return new Response('', { status: 504, statusText: 'Offline' });
}

async function trim(cache) {
  const keys = await cache.keys();
  if (keys.length > RUNTIME_MAX_ENTRIES) await Promise.all(keys.slice(0, keys.length - RUNTIME_MAX_ENTRIES).map(k => cache.delete(k)));
}

/* --------------------------------------------------------------- web push */
self.addEventListener('push', event => {
  let data = {};
  try { data = event.data ? event.data.json() : {}; } catch (_) {
    try { data = { body: event.data ? event.data.text() : '' }; } catch (_) {}
  }
  const title = data.title || 'ALIF';
  const options = {
    body: data.body || '',
    icon: data.icon || '/logo.png',
    badge: data.badge || '/logo.png',
    tag: data.tag || `alif-${Date.now()}`,
    data: { url: data.url || '/' },
    renotify: true
  };
  event.waitUntil(self.registration.showNotification(title, options));
});

self.addEventListener('notificationclick', event => {
  event.notification.close();
  const url = event.notification.data?.url || '/';
  event.waitUntil((async () => {
    const clients = await self.clients.matchAll({ type: 'window', includeUncontrolled: true });
    for (const client of clients) {
      if ('focus' in client) {
        try { await client.navigate(url); } catch (_) {}
        return client.focus();
      }
    }
    if (self.clients.openWindow) return self.clients.openWindow(url);
  })());
});
